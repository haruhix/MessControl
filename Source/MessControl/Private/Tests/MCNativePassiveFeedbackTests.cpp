bool SameSection(const FProcMeshSection* A,const FProcMeshSection* B)
{
    if(!A || !B)return A==B;
    if(A->ProcIndexBuffer!=B->ProcIndexBuffer || A->ProcVertexBuffer.Num()!=B->ProcVertexBuffer.Num())return false;
    for(int32 I=0;I<A->ProcVertexBuffer.Num();++I)
    {const auto& X=A->ProcVertexBuffer[I];const auto& Y=B->ProcVertexBuffer[I];if(X.Position!=Y.Position || X.Color!=Y.Color || X.Normal!=Y.Normal)return false;}
    return true;
}
