"""Drive shared menu BP functions on real UE ticks for a native motion review.

Frames are queued through the engine Shot command and captured after the 3D
viewport draw. Input injection is validated separately. Never sleeps in UE.
"""
import json
from pathlib import Path
import time
import unreal as u

world=u.EditorLevelLibrary.get_game_world()
assert world
cls=u.load_class(None,'/Game/UI/MainMenu3D/WBP_MainMenu3D.WBP_MainMenu3D_C')
lib=u.get_default_object(u.load_class(None,'/Script/UMG.WidgetBlueprintLibrary'))
widgets=lib.call_method('GetAllWidgetsOfClass',args=(world,cls,False))
assert len(widgets)==1
widget=widgets[0]
out=Path(u.Paths.project_dir())/'ArtSource/UI/MainMenu3D/20261015_refB_v1/Assembly/Review/Unreal_FunctionalBlocking_v03_FullRoute/Run08'
out.mkdir(parents=True,exist_ok=True)
assert not getattr(u,'_mc_accordion_review_handle',None),'Existing review callback must finish first'

schedule=[(0.,'ShowPage',0),(2.,'catalog',None),(4.5,'SelectDay',1),
    (7.5,'SelectDay',2),(10.,'OpenConnection',None),(12.5,'Back',None),
    (15.,'SelectDay',3),(18.,'StepDay',1),(21.,'StepDay',1),
    (24.,'StepDay',1),(27.,'StepDay',1),(29.5,'OpenConnection',None),
    (31.5,'StepDay',-1),(34.5,'Back',None),(37.,'Back',None),
    (39.,'catalog',None),(42.,'SelectDay',3),(45.,'Back',None),(47.5,'Back',None)]
state={'started':time.monotonic(),'started_wall':time.time(),'index':0,'actions':[],'samples':[],'last_sample':-1.}
capture={'started_monotonic':state['started'],'requested_fps':12.,'frames':[],
    'source':'Engine Shot SHOWUI: UGameViewportClient.ProcessScreenShots after the actual 3D viewport draw',
    'timing':'Actual screenshot file completion times relative to capture start; no invented poses'}
pending=None
last_request=-1.
mouth_actors={i:u.GameplayStatics.get_all_actors_with_tag(world,'Menu3D_DAY0'+str(i))[0] for i in range(1,8)}

def actor_hidden(actor):
    try:return bool(actor.get_editor_property('hidden'))
    except Exception:return None

def sample(elapsed):
    first=widget.get_editor_property('WindowFirstDay')
    heights=[widget.get_editor_property('Day'+str(i)+'Size').get_editor_property('height_override') for i in range(1,8)]
    state['samples'].append({'elapsed':elapsed,'page':widget.get_editor_property('PageIndex'),
        'selected':widget.get_editor_property('SelectedDay'),'active':widget.get_editor_property('ActiveDay'),
        'day_counter':str(widget.get_editor_property('DayCounter').get_text()),
        'wheel_accumulator':widget.get_editor_property('WheelAccumulator'),
        'window_first':first,'scroll_offset':widget.get_editor_property('DayScroll').get_scroll_offset(),
        'heights':heights,'three_row_sum':sum(heights[max(0,first-1):max(0,first-1)+3]),
        'openness':[widget.get_editor_property('Open'+str(i)) for i in range(1,8)],
        'mouths':[{'day':i,'hidden':actor_hidden(actor),
            'component_hidden':actor.get_component_by_class(u.SkeletalMeshComponent).get_editor_property('hidden_in_game'),
            'world_z':actor.get_actor_location().z,
            'pose_weights':{name:actor.get_component_by_class(u.SkeletalMeshComponent).get_morph_target(name)
                for name in ('Pose_000','Pose_025','Pose_050','Pose_075')}} for i,actor in mouth_actors.items()]})

def finish(error=None):
    u.unregister_slate_post_tick_callback(u._mc_accordion_review_handle)
    u._mc_accordion_review_handle=None
    state['purpose']='Actual native PIE; shared BP functions drive review. Physical wheel checked separately.'
    state['error']=error
    (out/'native_route_actual_states.json').write_text(json.dumps(state,indent=2),encoding='utf8')
    capture['error']=error
    (out/'capture_receipt.json').write_text(json.dumps(capture,indent=2),encoding='utf8')
    u.log('MC_ACCORDION_NATIVE_REVIEW_FINISHED '+str(error))

def tick(delta):
    global pending,last_request
    try:
        elapsed=time.monotonic()-state['started']
        # This is a controlled shared-function route. Pointer delivery is a
        # separate test; ignore pending hover generated by resize/repaint here.
        widget.call_method('ResetPointerIntent')
        if pending is not None:
            path=out/pending['file']
            if path.is_file():
                capture['frames'].append(dict(pending,time=path.stat().st_mtime-state['started_wall']))
                pending=None
            elif elapsed-last_request>5.:
                raise RuntimeError('Engine screenshot request did not complete within five seconds')
        while state['index']<len(schedule) and elapsed>=schedule[state['index']][0]:
            at,action,value=schedule[state['index']]
            if action=='catalog':
                # Exercise the actual authored Main/Play entry event; Blueprint
                # state variables are intentionally not instance-editable.
                widget.get_editor_property('PlayButton').on_clicked.broadcast()
            elif value is None:widget.call_method(action)
            else:widget.call_method(action,args=(value,))
            state['actions'].append({'elapsed':elapsed,'action':action,'value':value})
            state['index']+=1
        if elapsed-state['last_sample']>=.25:
            sample(elapsed);state['last_sample']=elapsed
        if elapsed>=50.:
            if pending is None:finish()
        elif pending is None and elapsed-last_request>=1./capture['requested_fps']:
            pending={'file':f'frame_{len(capture["frames"]):04d}.png','request_time':elapsed}
            last_request=elapsed
            path=(out/pending['file']).as_posix()
            u.SystemLibrary.execute_console_command(world,'Shot SHOWUI filename='+path+' -nosuffix')
    except Exception as error:
        finish(str(error));raise

u._mc_accordion_review_handle=u.register_slate_post_tick_callback(tick)
u.log('MC_ACCORDION_NATIVE_REVIEW_STARTED')
